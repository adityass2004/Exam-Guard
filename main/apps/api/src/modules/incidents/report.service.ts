import { prisma } from '../../lib/prisma.js';
import { AppError } from '../../lib/errors.js';
import { INCIDENT_STANDING_DISCLAIMER } from './incidents.service.js';
import { formatCsvRow } from './csv.js';

function escapeHtml(str: any): string {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export class IncidentReportService {
  async generateReport(
    incidentId: string,
    adminUserId: string,
    format: 'csv' | 'html',
    _includeImages: boolean = false
  ): Promise<{ contentType: string; content: string; filename: string }> {
    const incident = await prisma.securityTrigger.findUnique({
      where: { id: incidentId },
      include: {
        studentUser: {
          select: {
            id: true,
            fullName: true,
            email: true,
            studentProfile: true,
          },
        },
        exam: true,
        session: true,
        evidence: true,
        investigationLogs: {
          include: { adminUser: { select: { fullName: true } } },
          orderBy: { createdAt: 'asc' },
        },
      },
    });

    if (!incident) {
      throw new AppError('NOT_FOUND', 404, 'Security incident not found');
    }

    const admin = await prisma.user.findUnique({
      where: { id: adminUserId },
      select: { fullName: true },
    });

    // Audit and investigation log
    await prisma.$transaction(async (tx) => {
      await tx.adminAuditLog.create({
        data: {
          actorUserId: adminUserId,
          actorRole: 'ADMIN',
          action: 'EXPORT_GENERATED',
          entityType: 'SECURITY_TRIGGER',
          entityId: incident.id,
          after: {
            format,
            incidentCode: incident.incidentCode,
          },
        },
      });

      await tx.adminInvestigationLog.create({
        data: {
          triggerId: incident.id,
          adminUserId,
          action: 'REPORT_EXPORTED',
          note: `Incident report exported in ${format.toUpperCase()} format`,
        },
      });
    });

    const filename = `Incident-${incident.incidentCode}.${format}`;

    if (format === 'csv') {
      const rows: string[] = [];

      // Section 1: Incident Metadata
      rows.push(formatCsvRow(['FIELD', 'VALUE']));
      rows.push(formatCsvRow(['Incident Code', incident.incidentCode]));
      rows.push(formatCsvRow(['Trigger Type', incident.triggerType]));
      rows.push(formatCsvRow(['Severity', incident.severity]));
      rows.push(formatCsvRow(['Status', incident.status]));
      rows.push(formatCsvRow(['Disposition', incident.disposition || 'PENDING']));
      rows.push(formatCsvRow(['First Detected', incident.firstDetectedAt.toISOString()]));
      rows.push(formatCsvRow(['Last Detected', incident.lastDetectedAt.toISOString()]));
      rows.push(formatCsvRow(['Recovered At', incident.recoveredAt?.toISOString() || 'N/A']));
      rows.push(formatCsvRow(['Occurrence Count', incident.occurrenceCount]));
      rows.push(formatCsvRow(['First Match Score (%)', incident.firstSimilarityPct ?? 'N/A']));
      rows.push(formatCsvRow(['Worst Match Score (%)', incident.worstSimilarityPct ?? 'N/A']));
      rows.push(formatCsvRow(['Evidence Status', incident.evidenceStatus]));
      rows.push(formatCsvRow(['Evidence SHA-256', incident.evidence?.sha256 || 'N/A']));
      rows.push(formatCsvRow(['Candidate Name', incident.studentUser.fullName]));
      rows.push(formatCsvRow(['Candidate Email', incident.studentUser.email]));
      rows.push(formatCsvRow(['Student ID', incident.studentUser.studentProfile?.studentId || 'N/A']));
      rows.push(formatCsvRow(['Exam Title', incident.exam.title]));
      rows.push(formatCsvRow(['Session ID', incident.sessionId]));
      rows.push(formatCsvRow(['Report Generated At', new Date().toISOString()]));
      rows.push(formatCsvRow(['Generated By Admin', admin?.fullName || 'Administrator']));
      rows.push(formatCsvRow(['Standing Notice', INCIDENT_STANDING_DISCLAIMER]));
      rows.push('');

      // Section 2: Investigation Log
      rows.push(formatCsvRow(['INVESTIGATION TIMELINE']));
      rows.push(formatCsvRow(['Timestamp', 'Admin', 'Action', 'Disposition', 'Notes']));
      for (const log of incident.investigationLogs) {
        rows.push(
          formatCsvRow([
            log.createdAt.toISOString(),
            log.adminUser.fullName,
            log.action,
            log.disposition || '',
            log.note || '',
          ])
        );
      }

      return {
        contentType: 'text/csv; charset=utf-8',
        content: rows.join('\r\n'),
        filename,
      };
    } else {
      // HTML format - Clean print-friendly report
      const investigationRowsHtml = incident.investigationLogs
        .map(
          (log) => `<tr>
            <td>${escapeHtml(log.createdAt.toISOString())}</td>
            <td>${escapeHtml(log.adminUser.fullName)}</td>
            <td><strong>${escapeHtml(log.action)}</strong></td>
            <td>${escapeHtml(log.disposition || '—')}</td>
            <td>${escapeHtml(log.note || '—')}</td>
          </tr>`
        )
        .join('');

      const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>ExamGuard Incident Report — ${escapeHtml(incident.incidentCode)}</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; color: #1e293b; padding: 40px; margin: 0; line-height: 1.5; font-size: 13px; }
    h1 { font-size: 20px; font-weight: bold; margin-bottom: 4px; }
    .badge { display: inline-block; padding: 2px 8px; border-radius: 4px; font-size: 11px; font-weight: bold; text-transform: uppercase; }
    .badge-critical { background: #fee2e2; color: #991b1b; }
    .badge-high { background: #ffedd5; color: #9a3412; }
    .badge-medium { background: #fef3c7; color: #92400e; }
    .badge-low { background: #f1f5f9; color: #475569; }
    .disclaimer { background: #f8fafc; border-left: 4px solid #64748b; padding: 12px 16px; margin: 20px 0; font-style: italic; color: #475569; }
    table { width: 100%; border-collapse: collapse; margin-top: 12px; margin-bottom: 24px; }
    th, td { border: 1px solid #e2e8f0; padding: 8px 12px; text-align: left; }
    th { background: #f8fafc; font-weight: 600; }
    .meta-grid { display: grid; grid-template-columns: 1fr 1fr; gap: 20px; margin-top: 16px; }
    @media print { body { padding: 0; } }
  </style>
</head>
<body>
  <h1>Security Incident Investigation Report</h1>
  <div>Incident Code: <strong>${escapeHtml(incident.incidentCode)}</strong> &bull; Status: <strong>${escapeHtml(incident.status)}</strong></div>

  <div class="disclaimer">
    <strong>Notice:</strong> ${escapeHtml(INCIDENT_STANDING_DISCLAIMER)}
  </div>

  <div class="meta-grid">
    <div>
      <h3>Incident Details</h3>
      <table>
        <tr><th>Trigger Type</th><td>${escapeHtml(incident.triggerType)}</td></tr>
        <tr><th>Severity</th><td><span class="badge badge-${incident.severity.toLowerCase()}">${escapeHtml(incident.severity)}</span></td></tr>
        <tr><th>Disposition</th><td>${escapeHtml(incident.disposition || 'UNREVIEWED')}</td></tr>
        <tr><th>First Detected</th><td>${escapeHtml(incident.firstDetectedAt.toISOString())}</td></tr>
        <tr><th>Last Detected</th><td>${escapeHtml(incident.lastDetectedAt.toISOString())}</td></tr>
        <tr><th>Recovered At</th><td>${escapeHtml(incident.recoveredAt?.toISOString() || 'Not recovered')}</td></tr>
        <tr><th>Occurrence Count</th><td>${escapeHtml(incident.occurrenceCount)}</td></tr>
        <tr><th>Worst Similarity Score</th><td>${escapeHtml(incident.worstSimilarityPct != null ? `${incident.worstSimilarityPct}%` : 'N/A')}</td></tr>
        <tr><th>Evidence SHA-256</th><td><code>${escapeHtml(incident.evidence?.sha256 || 'N/A')}</code></td></tr>
      </table>
    </div>

    <div>
      <h3>Candidate & Examination</h3>
      <table>
        <tr><th>Candidate Name</th><td>${escapeHtml(incident.studentUser.fullName)}</td></tr>
        <tr><th>Candidate Email</th><td>${escapeHtml(incident.studentUser.email)}</td></tr>
        <tr><th>Student ID</th><td>${escapeHtml(incident.studentUser.studentProfile?.studentId || 'N/A')}</td></tr>
        <tr><th>Examination</th><td>${escapeHtml(incident.exam.title)}</td></tr>
        <tr><th>Exam Duration</th><td>${escapeHtml(incident.exam.durationMinutes)} minutes</td></tr>
        <tr><th>Session ID</th><td><code>${escapeHtml(incident.sessionId)}</code></td></tr>
        <tr><th>Report Generated</th><td>${escapeHtml(new Date().toISOString())}</td></tr>
        <tr><th>Generated By</th><td>${escapeHtml(admin?.fullName || 'Administrator')}</td></tr>
      </table>
    </div>
  </div>

  <h3>Investigation Timeline</h3>
  <table>
    <thead>
      <tr>
        <th>Timestamp</th>
        <th>Proctor / Admin</th>
        <th>Action</th>
        <th>Disposition</th>
        <th>Notes</th>
      </tr>
    </thead>
    <tbody>
      ${investigationRowsHtml || '<tr><td colspan="5" style="text-align: center; color: #94a3b8;">No investigation notes recorded</td></tr>'}
    </tbody>
  </table>
</body>
</html>`;

      return {
        contentType: 'text/html; charset=utf-8',
        content: html,
        filename,
      };
    }
  }
}

export const incidentReportService = new IncidentReportService();
